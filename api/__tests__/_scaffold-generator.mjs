#!/usr/bin/env node
// Usage: node api/__tests__/_scaffold-generator.mjs
// Emits one .test.mjs file per handler that doesn't already have one.
import { readdir, writeFile, access } from 'node:fs/promises';
import { join } from 'node:path';

const API_DIR = new URL('../', import.meta.url).pathname;
const TEST_DIR = new URL('./', import.meta.url).pathname;

const handlers = (await readdir(API_DIR))
  .filter(f => f.endsWith('.js') && !f.startsWith('_'));

for (const handler of handlers) {
  const testName = handler.replace('.js', '.test.mjs');
  const testPath = join(TEST_DIR, testName);
  try { await access(testPath); continue; } catch {}

  const content = `/**
 * ${handler} characterization tests
 * Generated by api/__tests__/_scaffold-generator.mjs
 *
 * TODO: Fill in handler-specific assertions. Each test currently validates
 * only the response contract (status code is 2xx/4xx/5xx appropriately,
 * body is present). Customize the upstream mock responses for real coverage.
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mockReq, mockRes, mockFetch } from './_test-utils.mjs';

let handler;
try {
  handler = (await import('../${handler}')).default
    ?? (await import('../${handler}'));
} catch (err) {
  console.warn('Handler ${handler} failed to import:', err.message);
  handler = null;
}

test('${handler}: rejects unsupported methods', async () => {
  if (!handler) return;
  const req = mockReq({ method: 'DELETE' });
  const res = mockRes();
  await handler(req, res);
  assert.ok(res.statusCode === 405 || res.statusCode === 400 || res.statusCode === 200,
    'should handle or reject unsupported methods');
});

test('${handler}: handles missing query params gracefully', async () => {
  if (!handler) return;
  const req = mockReq({ query: {} });
  const res = mockRes();
  const restoreFetch = mockFetch(new Map([
    ['http', { status: 200, json: {} }],
  ]));
  try { await handler(req, res); } catch {} finally { restoreFetch(); }
  assert.ok(res.ended || res.body !== null, 'should respond');
});
`;

  await writeFile(testPath, content);
  console.log('Created', testName);
}
