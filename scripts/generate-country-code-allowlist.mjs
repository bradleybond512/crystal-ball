#!/usr/bin/env node
/**
 * Generates server/_shared/country-codes.ts: the country codes the server
 * accepts for country-scoped RPCs (R4-SEC-007), plus the two helpers that use
 * them. The module is self-contained (no imports) so Node's type stripping can
 * load it directly in tests.
 *
 * Source of truth is the app's own map data, so the allowlist matches exactly
 * what a map click can produce:
 *   - every two-letter `ISO3166-1-Alpha-2` code in public/data/countries.geojson;
 *   - after the renderer's POLITICAL_OVERRIDES (src/services/country-geometry.ts);
 *   - plus the TIER1_COUNTRIES keys the brief prompt names.
 *
 * Usage: node scripts/generate-country-code-allowlist.mjs [--check]
 *   --check exits 1 when the committed file is out of date.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const OUT = path.join(root, 'server/_shared/country-codes.ts');
const TWO_LETTER = /^[A-Z]{2}$/;

function readOverrides() {
  const source = readFileSync(path.join(root, 'src/services/country-geometry.ts'), 'utf8');
  const block = source.match(/POLITICAL_OVERRIDES[^=]*=\s*\{([^}]*)\}/);
  if (!block) throw new Error('POLITICAL_OVERRIDES not found in country-geometry.ts');
  return Object.fromEntries([...block[1].matchAll(/'([^']+)'\s*:\s*'([^']+)'/g)].map((m) => [m[1], m[2]]));
}

function readTier1() {
  const source = readFileSync(path.join(root, 'server/crystalball/intelligence/v1/_shared.ts'), 'utf8');
  const start = source.indexOf('TIER1_COUNTRIES');
  if (start === -1) throw new Error('TIER1_COUNTRIES not found');
  const body = source.slice(start, source.indexOf('};', start));
  return [...body.matchAll(/\b([A-Z]{2})\s*:/g)].map((m) => m[1]);
}

export function buildCountryCodes() {
  const overrides = readOverrides();
  const geo = JSON.parse(readFileSync(path.join(root, 'public/data/countries.geojson'), 'utf8'));
  const codes = new Set();
  for (const feature of geo.features ?? []) {
    const raw = String(feature?.properties?.['ISO3166-1-Alpha-2'] ?? '').toUpperCase();
    const code = overrides[raw] ?? raw;
    if (TWO_LETTER.test(code)) codes.add(code);
  }
  for (const code of readTier1()) codes.add(code);
  return [...codes].sort();
}

export function renderModule(codes) {
  const rows = [];
  for (let i = 0; i < codes.length; i += 16) {
    const quoted = codes.slice(i, i + 16).map((c) => JSON.stringify(c).replaceAll('"', "'"));
    rows.push(`  ${quoted.join(', ')},`);
  }
  return [
    '// GENERATED by scripts/generate-country-code-allowlist.mjs. Do not edit by hand.',
    '// Source: public/data/countries.geojson (after POLITICAL_OVERRIDES) plus TIER1_COUNTRIES.',
    `// ${codes.length} codes. Only a code in this set may reach an LLM prompt (R4-SEC-007).`,
    '',
    'export const COUNTRY_CODES: ReadonlySet<string> = new Set([',
    ...rows,
    ']);',
    '',
    'export function isAllowedCountryCode(code: unknown): code is string {',
    "  return typeof code === 'string' && COUNTRY_CODES.has(code);",
    '}',
    '',
    '/** Thrown for caller mistakes. The gateway error mapper turns `statusCode`',
    ' *  into the HTTP status and, for 4xx, returns the message to the caller. */',
    'export class BadRequestError extends Error {',
    '  statusCode: number;',
    '',
    '  constructor(message: string) {',
    '    super(message);',
    "    this.name = 'BadRequestError';",
    '    this.statusCode = 400;',
    '  }',
    '}',
    '',
  ].join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const next = renderModule(buildCountryCodes());
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(OUT, 'utf8'); } catch { /* missing */ }
    if (current !== next) {
      console.error('[country-codes] server/_shared/country-codes.ts is out of date; run node scripts/generate-country-code-allowlist.mjs');
      process.exit(1);
    }
    console.log('[country-codes] allowlist is current.');
  } else {
    writeFileSync(OUT, next);
    console.log(`[country-codes] wrote ${path.relative(root, OUT)}`);
  }
}
