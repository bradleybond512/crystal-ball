import type { StoryData } from './story-data';

// Public links stay disabled until a separately verified sharing service exists.
// This build-time flag never reads or writes a user preference.
export const PUBLIC_STORY_SHARING_ENABLED = false;

export function isPublicStorySharingEnabled(): boolean {
  return PUBLIC_STORY_SHARING_ENABLED;
}

// Deep link generator for story sharing
export function generateStoryDeepLink(
  countryCode: string,
  type?: 'ciianalysis' | 'convergence' | 'brief',
  score?: number,
  level?: string
): string | null;
export function generateStoryDeepLink(): string | null {
  // Public links remain unavailable; the overload preserves typed callers.
  return null;
}

// Parse deep link parameters
export function parseStoryParams(url: URL): { countryCode: string; type: string } | null {
  const countryCode = url.searchParams.get('c');
  if (!countryCode) return null;
  const type = url.searchParams.get('t');
  if (!type) return { countryCode, type: 'ciianalysis' };
  return { countryCode, type };
}

// Generate QR code data URL (simple implementation)
export function generateQRCode(data: string, size = 200): string {
  // Using a simple QR code library pattern
  // In production, use a library like qrcode or node-qrcode
  const canvas = document.createElement('canvas');
  canvas.width = size;
  canvas.height = size;
  const ctx = canvas.getContext('2d')!;

  // Placeholder - would use actual QR library
  ctx.fillStyle = '#ffffff';
  ctx.fillRect(0, 0, size, size);
  ctx.fillStyle = '#000000';
  ctx.font = '14px monospace';
  ctx.textAlign = 'center';
  ctx.fillText('Scan to view', size/2, size/2 - 10);
  ctx.fillText(data.slice(0, 20) + '...', size/2, size/2 + 10);

  return canvas.toDataURL('image/png');
}

// Convert 2-letter country code to flag emoji
function countryFlag(code: string): string {
  const upper = code.toUpperCase();
  if (upper.length !== 2) return '';
  // Slice single UTF-16 units to preserve legacy behavior for non-BMP inputs.
  return String.fromCodePoint(
 0x1_F1_E6 + upper.slice(0, 1).codePointAt(0)! - 65,
 0x1_F1_E6 + upper.slice(1, 2).codePointAt(0)! - 65
  );
}

// Share text templates for different platforms
class StoryShareText {
  static twitter(data: StoryData): string {
    return `${countryFlag(data.countryCode)} ${data.countryName} Intelligence Brief\n\n` +
 `Instability: ${StoryShareText.fallback(data.cii?.score, 'N/A')}/100 (${StoryShareText.fallback(data.cii?.level, 'N/A')})\n` +
 StoryShareText.criticalLine(data, '⚠️ ', ' critical threats\n') +
 `\nGenerated by @CrystalBallApp`;
  }

  static whatsapp(data: StoryData): string {
    return `${countryFlag(data.countryCode)} *${data.countryName} Intelligence Brief*\n\n` +
 `*Instability:* ${StoryShareText.fallback(data.cii?.score, 'N/A')}/100 (${StoryShareText.fallback(data.cii?.level, 'N/A')})\n` +
 `*Trend:* ${StoryShareText.fallback(data.cii?.trend, 'stable')}\n` +
 StoryShareText.criticalLine(data, '*⚠️ Critical:* ', '\n') +
 StoryShareText.highLine(data, '*🔴 High:* ', '\n') +
 `\nGenerated by Crystal Ball`;
  }

  static linkedin(data: StoryData): string {
    return `Intelligence Update: ${data.countryName}\n\n` +
 `Real-time instability assessment:\n` +
 `• Score: ${StoryShareText.fallback(data.cii?.score, 'N/A')}/100 (${StoryShareText.fallback(data.cii?.level, 'N/A')})\n` +
 `• 24h change: ${StoryShareText.linkedInChange(data)}%\n` +
 StoryShareText.criticalLine(data, '• Critical threats: ', '\n') +
 `\nData via Crystal Ball - Open source geopolitical intelligence`;
  }

  static telegram(data: StoryData): string {
    return `${countryFlag(data.countryCode)} *${data.countryName} Intelligence*\n\n` +
 `📊 Instability: *${StoryShareText.fallback(data.cii?.score, 'N/A')}/100* (${StoryShareText.fallback(data.cii?.level, 'N/A')})\n` +
 `📈 Trend: *${StoryShareText.fallback(data.cii?.trend, 'stable')}*\n` +
 StoryShareText.telegramChange(data) +
 StoryShareText.criticalLine(data, '🚨 Critical: *', '*\n') +
 StoryShareText.highLine(data, '🔴 High: *', '*\n') +
 `\nGenerated by Crystal Ball`;
  }

  static redditTitle(data: StoryData): string {
    return encodeURIComponent(`${data.countryName} Intelligence Brief - Crystal Ball`);
  }

  private static fallback(value: string | number | null | undefined, fallback: string): string {
    if (value) return `${value}`;
    return fallback;
  }

  private static criticalLine(data: StoryData, prefix: string, suffix: string): string {
    if (data.threats.critical > 0) return `${prefix}${data.threats.critical}${suffix}`;
    return '';
  }

  private static highLine(data: StoryData, prefix: string, suffix: string): string {
    if (data.threats.high > 0) return `${prefix}${data.threats.high}${suffix}`;
    return '';
  }

  private static linkedInChange(data: StoryData): string {
    if (!data.cii?.change24h) return 'N/A';
    const sign = data.cii.change24h > 0 ? '+' : '';
    return sign + data.cii.change24h;
  }

  private static telegramChange(data: StoryData): string {
    if (!data.cii?.change24h) return '';
    const sign = data.cii.change24h > 0 ? '+' : '';
    return `📉 24h: *${sign}${data.cii.change24h}*\n`;
  }
}

export const shareTexts = {
  twitter: (data: StoryData) => StoryShareText.twitter(data),
  whatsapp: (data: StoryData) => StoryShareText.whatsapp(data),
  linkedin: (data: StoryData) => StoryShareText.linkedin(data),
  telegram: (data: StoryData) => StoryShareText.telegram(data),
};

// Pre-generated share URLs
export function getShareUrls(data: StoryData): Record<string, string> {
  if (!isPublicStorySharingEnabled()) return {};
  const url = generateStoryDeepLink(data.countryCode, 'ciianalysis', data.cii?.score, data.cii?.level);
  if (!url) return {};
  const text = encodeURIComponent(shareTexts.twitter(data));

  return {
 twitter: `https://twitter.com/intent/tweet?text=${text}&url=${encodeURIComponent(url)}`,
 linkedin: `https://www.linkedin.com/sharing/share-offsite/?url=${encodeURIComponent(url)}`,
 reddit: `https://reddit.com/submit?url=${encodeURIComponent(url)}&title=${StoryShareText.redditTitle(data)}`,
 facebook: `https://www.facebook.com/sharer/sharer.php?u=${encodeURIComponent(url)}`,
 whatsapp: `https://wa.me/?text=${encodeURIComponent(shareTexts.whatsapp(data).replace('\n', '%0A'))}`,
 telegram: `https://t.me/share/url?url=${encodeURIComponent(url)}&text=${encodeURIComponent(shareTexts.telegram(data).replace('\n', '%0A'))}`,
  };
}
